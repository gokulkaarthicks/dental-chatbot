"""Conversation and message tables for the DeepSeek receptionist.

History fidelity
----------------
Phase 2 replays the *full* thread to the model on every turn (no summarisation).
To do that faithfully we persist every turn shape, not just plain chat:

* ``patient``      - text typed by the visitor
* ``assistant``    - the model's reply, optionally with ``tool_calls`` JSON
* ``tool``         - a tool result, linked to the assistant message that called it
* ``system``       - staff/system notices

``tool_calls`` and ``tool_call_id`` are stored in the ``metadata`` JSON column.
That column is **internal only**: no API response serialises it, so provider
payloads and internal tool names never reach the browser.
"""

from __future__ import annotations

from datetime import datetime
from typing import TYPE_CHECKING, Any

from sqlalchemy import JSON, ForeignKey, Index, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import (
    Base,
    ConversationStatus,
    MessageRole,
    TimestampMixin,
    UTCDateTime,
)

if TYPE_CHECKING:
    from app.models.proposals import BookingProposal
    from app.models.sessions import PatientSession


class Conversation(Base, TimestampMixin):
    """One chat thread.

    ``public_id`` is generated by the server and is **not** a credential: every
    read/write goes through the patient session token, and the conversation is
    only reachable when it belongs to the calling session.
    """

    __tablename__ = "conversations"

    id: Mapped[int] = mapped_column(primary_key=True)
    public_id: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)
    patient_session_id: Mapped[int | None] = mapped_column(
        ForeignKey("patient_sessions.id", ondelete="CASCADE")
    )
    status: Mapped[str] = mapped_column(
        String(16), nullable=False, default=ConversationStatus.ACTIVE.value
    )
    title: Mapped[str | None] = mapped_column(String(120))
    caller_phone: Mapped[str | None] = mapped_column(String(32))
    patient_id: Mapped[int | None] = mapped_column(ForeignKey("patients.id", ondelete="SET NULL"))
    reset_generation: Mapped[str] = mapped_column(String(36), nullable=False)
    started_at: Mapped[datetime] = mapped_column(UTCDateTime(), nullable=False)
    ended_at: Mapped[datetime | None] = mapped_column(UTCDateTime())
    last_message_at: Mapped[datetime | None] = mapped_column(UTCDateTime())
    # The canonical scheduling intent for this thread.  Chat history remains
    # conversational context, but participant/type/date changes must update one
    # structured request rather than asking each model turn to reconstruct it.
    scheduling_request: Mapped[dict[str, Any] | None] = mapped_column(JSON)

    patient_session: Mapped[PatientSession | None] = relationship(back_populates="conversations")
    messages: Mapped[list[Message]] = relationship(
        back_populates="conversation",
        cascade="all, delete-orphan",
        order_by="Message.id",
    )
    proposals: Mapped[list[BookingProposal]] = relationship(
        back_populates="conversation", cascade="all, delete-orphan"
    )

    __table_args__ = (
        Index("ix_conversations_session", "patient_session_id"),
        Index("ix_conversations_phone", "caller_phone"),
        Index("ix_conversations_generation", "reset_generation"),
        Index("ix_conversations_status_started", "status", "started_at"),
    )


class Message(Base):
    """A single turn in a conversation.

    ``content`` is ``TEXT NOT NULL``; an assistant turn that only issues tool
    calls stores an empty string, which is what the provider accepts on replay.
    """

    __tablename__ = "messages"

    id: Mapped[int] = mapped_column(primary_key=True)
    conversation_id: Mapped[int] = mapped_column(
        ForeignKey("conversations.id", ondelete="CASCADE"), nullable=False
    )
    role: Mapped[str] = mapped_column(String(16), nullable=False)
    content: Mapped[str] = mapped_column(Text, nullable=False, default="")
    sequence: Mapped[int] = mapped_column(Integer, nullable=False)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime(), nullable=False)
    finished_at: Mapped[datetime | None] = mapped_column(UTCDateTime())

    # Provider-facing bookkeeping. Never serialised to clients.
    tool_calls: Mapped[list[dict[str, Any]] | None] = mapped_column("metadata", JSON)
    tool_call_id: Mapped[str | None] = mapped_column(String(64))
    tool_name: Mapped[str | None] = mapped_column(String(64))

    # Phase 3: interactive UI cards (slot grids, proposals, confirmations)
    # produced during this assistant turn. Persisted so a refresh replays the
    # same cards instead of losing them; each card carries only ids that
    # already exist in SQLite.
    cards: Mapped[list[dict[str, Any]] | None] = mapped_column(JSON)

    conversation: Mapped[Conversation] = relationship(back_populates="messages")

    __table_args__ = (
        Index("ix_messages_conversation_sequence", "conversation_id", "sequence", unique=True),
        Index("ix_messages_role", "role"),
        Index("ix_messages_tool_call", "tool_call_id"),
    )

    def role_is_valid(self) -> bool:
        return self.role in {role.value for role in MessageRole}
