def _seed_providers(
    session: Session, tenant: TenantSeed, counters: defaultdict[str, int]
) -> dict[str, Provider]:
    plan = tenant.plan
    keys = [item.key for item in plan.providers]
    existing = {
        provider.seed_key: provider
        for provider in session.scalars(
            select(Provider).where(
                Provider.clinic_id == tenant.clinic_id, Provider.seed_key.in_(keys)
            )
        )
    }
    result: dict[str, Provider] = {}
    for fixture in plan.providers:
        provider = existing.get(fixture.key)
        if provider is None:
            provider = Provider(
                clinic_id=tenant.clinic_id,
                seed_key=fixture.key,
                full_name=fixture.full_name,
                credentials=fixture.credentials,
                email=fixture.email,
                bio=fixture.bio,
                active=True,
            )
            session.add(provider)
            counters["providers"] += 1
        else:
            counters["skipped"] += 1
        session.flush()
        result[fixture.key] = provider

        known = {specialty.specialty for specialty in provider.specialties}
        for specialty in fixture.specialties:
            if specialty not in known:
                session.add(
                    ProviderSpecialty(
                        clinic_id=tenant.clinic_id,
                        provider_id=provider.id,
                        specialty=specialty,
                    )
                )
    session.flush()
    return result


def _seed_families_and_patients(
    session: Session, tenant: TenantSeed, counters: defaultdict[str, int]
) -> tuple[dict[str, Patient], dict[str, FamilyGroup]]:
    plan = tenant.plan
    families: dict[str, FamilyGroup] = {}
    for fixture in plan.families:
        group = session.scalar(
            select(FamilyGroup).where(
                FamilyGroup.clinic_id == tenant.clinic_id,
                FamilyGroup.seed_key == fixture.key,
            )
        )
        if group is None:
            group = FamilyGroup(
                clinic_id=tenant.clinic_id,
                seed_key=fixture.key,
                name=fixture.name,
                shared_phone=fixture.shared_phone,
                notes=fixture.notes,
            )
            session.add(group)
            counters["families"] += 1
        else:
            counters["skipped"] += 1
        session.flush()
        families[fixture.key] = group

    patients: dict[str, Patient] = {}
    for fixture in plan.patients:
        patient = session.scalar(
            select(Patient).where(
                Patient.clinic_id == tenant.clinic_id, Patient.seed_key == fixture.key
            )
        )
        if patient is None:
            patient = Patient(
                clinic_id=tenant.clinic_id,
                seed_key=fixture.key,
                full_name=fixture.full_name,
                phone=fixture.phone,
                date_of_birth=date.fromisoformat(fixture.dob),
                insurance_provider=fixture.insurance_provider,
                insurance_member_id=fixture.insurance_member_id,
                notes=fixture.notes,
            )
            session.add(patient)
            counters["patients"] += 1
        else:
            counters["skipped"] += 1
        session.flush()
        patients[fixture.key] = patient

    for fixture in plan.patients:
        if fixture.family_group_key is None:
            continue
        group = families[fixture.family_group_key]
        patient = patients[fixture.key]
        membership = session.scalar(
            select(FamilyMember).where(
                FamilyMember.family_group_id == group.id,
                FamilyMember.patient_id == patient.id,
            )
        )
        if membership is None:
            session.add(
                FamilyMember(
                    clinic_id=tenant.clinic_id,
                    family_group_id=group.id,
                    patient_id=patient.id,
                    relation_to_primary=fixture.relationship or "member",
                    is_primary_contact=fixture.is_primary_contact,
                )
            )
        else:
            counters["skipped"] += 1
    session.flush()
    return patients, families


def _seed_appointment_types(
    session: Session, tenant: TenantSeed, counters: defaultdict[str, int]
) -> dict[str, AppointmentType]:
    plan = tenant.plan
    codes = [item.code for item in plan.appointment_types]
    existing = {
        item.code: item
        for item in session.scalars(
            select(AppointmentType).where(
                AppointmentType.clinic_id == tenant.clinic_id,
                AppointmentType.code.in_(codes),
            )
        )
    }
    result: dict[str, AppointmentType] = {}
    for index, fixture in enumerate(plan.appointment_types):
        item = existing.get(fixture.code)
        if item is None:
            item = AppointmentType(
                clinic_id=tenant.clinic_id,
                code=fixture.code,
                name=fixture.name,
                description=fixture.description,
                duration_minutes=fixture.duration_minutes,
                is_emergency=fixture.is_emergency,
                required_specialty=fixture.required_specialty,
                sort_order=index,
            )
            session.add(item)
            counters["appointment_types"] += 1
        else:
            counters["skipped"] += 1
        session.flush()
        result[fixture.code] = item
    return result


def _seed_slots(
    session: Session,
    tenant: TenantSeed,
    providers: dict[str, Provider],
    *,
    today: date,
    anchor: date,
    counters: defaultdict[str, int],
) -> None:
    """Create the horizon-long grid for days that have no slots yet.

    The grid is built from the tenant's own config, so the 20-minute Eastern
    practice gets its 9-to-5 day in 20-minute steps and the 30-minute Pacific one
    gets 8-to-6 in 30-minute steps, from one code path.
    """
    config = tenant.config
    plan = tenant.plan
    days = [today + timedelta(days=offset) for offset in range(config.seed_horizon_days)]

    for provider_fixture in plan.providers:
        provider = providers[provider_fixture.key]
        covered_days = _covered_slot_days(session, tenant, provider.id)
        rows: list[dict] = []
        for day in days:
            if not config.is_open_weekday(day):
                continue
            if day.isoformat() in covered_days:
                counters["skipped"] += 1
                continue
            cursor = datetime.combine(day, config.open_time)
            close = datetime.combine(day, config.close_time)
            while cursor < close:
                rows.append(
                    {
                        "clinic_id": tenant.clinic_id,
                        "provider_id": provider.id,
                        "starts_at": cursor,
                        "ends_at": cursor + config.slot_length,
                        "status": SlotStatus.AVAILABLE.value,
                    }
                )
                cursor += config.slot_length
        if rows:
            # A Core bulk insert bypasses the ORM events, so the tenant stamp has
            # to be in the rows themselves -- it is above.
            session.execute(AvailabilitySlot.__table__.insert(), rows)
            counters["slots"] += len(rows)

    _backfill_historical_slots(session, tenant, providers, anchor=anchor, counters=counters)
    session.flush()


def _backfill_historical_slots(
    session: Session,
    tenant: TenantSeed,
    providers: dict[str, Provider],
    *,
    anchor: date,
    counters: defaultdict[str, int],
) -> None:
    """Materialise slots on past days that fixture appointments need.

    The forward grid intentionally starts today, but the demo includes completed
    visits. Only the exact business days those visits touch are created, so the
    historical data stays small and reproducible.
    """
    config = tenant.config
    needed: dict[int, set[date]] = defaultdict(set)
    for fixture in tenant.plan.past:
        provider = providers[fixture.provider_key]
        needed[provider.id].add(anchor + timedelta(days=fixture.day_offset))

    earliest = anchor - timedelta(days=config.seed_horizon_days)
    for provider_id, days in needed.items():
        existing_days = _covered_slot_days(
            session,
            tenant,
            provider_id,
            after=datetime.combine(earliest, datetime.min.time()),
        )
        rows: list[dict] = []
        for day in sorted(days):
            if not config.is_open_weekday(day) or day.isoformat() in existing_days:
                continue
            cursor = datetime.combine(day, config.open_time)
            close = datetime.combine(day, config.close_time)
            while cursor < close:
                rows.append(
                    {
                        "clinic_id": tenant.clinic_id,
                        "provider_id": provider_id,
                        "starts_at": cursor,
                        "ends_at": cursor + config.slot_length,
                        "status": SlotStatus.AVAILABLE.value,
                    }
                )
                cursor += config.slot_length
        if rows:
            session.execute(AvailabilitySlot.__table__.insert(), rows)
            counters["slots"] += len(rows)
    session.flush()


def _seed_appointments(
    session: Session,
    tenant: TenantSeed,
    providers: dict[str, Provider],
    patients: dict[str, Patient],
    types: dict[str, AppointmentType],
    families: dict[str, FamilyGroup],
    anchor: date,
    counters: defaultdict[str, int],
) -> None:
    config = tenant.config
    plan = tenant.plan
    now_local = config.now()
    fixtures: list[AppointmentFixture] = [*plan.upcoming, *plan.past]
    patient_groups = {fixture.key: fixture.family_group_key for fixture in plan.patients}

    for fixture in fixtures:
        if session.scalar(
            select(Appointment).where(
                Appointment.clinic_id == tenant.clinic_id,
                Appointment.seed_key == fixture.key,
            )
        ):
            counters["skipped"] += 1
            continue

        provider = providers[fixture.provider_key]
        appointment_type = types[fixture.type_code]
        starts_at, ends_at = appointment_bounds(fixture, anchor, config, plan.appointment_types)

        interval_starts: list[datetime] = []
        cursor = starts_at
        while cursor < ends_at:
            interval_starts.append(cursor)
            cursor += config.slot_length

        slots = [_slot_at(session, tenant, provider.id, start) for start in interval_starts]
        if any(slot is None for slot in slots):
            logger.warning(
                "Fixture %s targets %s with no availability grid (closed day or "
                "outside the seeded horizon); skipped.",
                fixture.key,
                starts_at.isoformat(timespec="minutes"),
            )
            counters["claim_conflicts"] += 1
            continue
        if any(slot.status != SlotStatus.AVAILABLE.value for slot in slots if slot):
            logger.warning("Fixture %s overlaps an already-occupied slot; skipped.", fixture.key)
            counters["claim_conflicts"] += 1
            continue

        status = (
            AppointmentStatus.COMPLETED.value
            if starts_at < now_local
            else AppointmentStatus.BOOKED.value
        )
        appointment = Appointment(
            clinic_id=tenant.clinic_id,
            seed_key=fixture.key,
            patient_id=patients[fixture.patient_key].id,
            provider_id=provider.id,
            appointment_type_id=appointment_type.id,
            starts_at=starts_at,
            ends_at=ends_at,
            duration_minutes=appointment_type.duration_minutes,
            status=status,
            reason=fixture.reason,
            created_by="seed",
            family_group_id=(
                families[patient_groups[fixture.patient_key]].id
                if patient_groups.get(fixture.patient_key)
                else None
            ),
        )
        session.add(appointment)
        session.flush()

        for slot in slots:
            assert slot is not None  # guarded above
            slot.status = SlotStatus.OCCUPIED.value
            session.add(
                SlotClaim(
                    clinic_id=tenant.clinic_id,
                    availability_slot_id=slot.id,
                    appointment_id=appointment.id,
                    active=True,
                )
            )
        counters["appointments"] += 1
    session.flush()


def _seed_staff(
    session: Session, tenant: TenantSeed, counters: defaultdict[str, int]
) -> dict[str, StaffUser]:
    keys = [item.key for item in tenant.plan.staff]
    existing = {
        user.seed_key: user
        for user in session.scalars(
            select(StaffUser).where(
                StaffUser.clinic_id == tenant.clinic_id, StaffUser.seed_key.in_(keys)
            )
        )
    }
    result: dict[str, StaffUser] = {}
    for fixture in tenant.plan.staff:
        user = existing.get(fixture.key)
        if user is None:
            user = StaffUser(
                clinic_id=tenant.clinic_id,
                seed_key=fixture.key,
                email=fixture.email,
                display_name=fixture.display_name,
                role=fixture.role,
                username=fixture.username,
                password_hash=hash_password(fixture.demo_password),
                active=True,
            )
            session.add(user)
            counters["staff"] += 1
        else:
            # Backfill the Phase 4 login fields onto accounts seeded before the
            # dashboard existed: an upgraded demo must still be able to sign in
            # as the documented ``root`` user, and its password must stay hashed.
            if fixture.username and user.username != fixture.username:
                user.username = fixture.username
                user.password_hash = hash_password(fixture.demo_password)
            counters["skipped"] += 1
        session.flush()
        result[fixture.key] = user
    return result


def _seed_alerts(
    session: Session,
    tenant: TenantSeed,
    patients: dict[str, Patient],
    counters: defaultdict[str, int],
) -> None:
    for fixture in tenant.plan.alerts:
        exists = session.scalar(
            select(StaffAlert).where(
                StaffAlert.clinic_id == tenant.clinic_id,
                StaffAlert.kind == fixture.kind,
                StaffAlert.message == fixture.message,
            )
        )
        if exists:
            counters["skipped"] += 1
            continue
        session.add(
            StaffAlert(
                clinic_id=tenant.clinic_id,
                patient_id=patients[fixture.patient_key].id if fixture.patient_key else None,
                kind=fixture.kind,
                severity=fixture.severity,
                message=fixture.message,
                status=fixture.status,
            )
        )
        counters["alerts"] += 1
    session.flush()


def _seed_pending_requests(
    session: Session,
    tenant: TenantSeed,
    patients: dict[str, Patient],
    staff: dict[str, StaffUser],
    counters: defaultdict[str, int],
) -> None:
    staff_queue = deque(staff.values())
    for fixture in tenant.plan.pending_requests:
        patient = patients[fixture.patient_key]
        exists = session.scalar(
            select(PendingRequest).where(
                PendingRequest.clinic_id == tenant.clinic_id,
                PendingRequest.details == fixture.details,
                PendingRequest.patient_id == patient.id,
            )
        )
        if exists:
            counters["skipped"] += 1
            continue
        assigned_to = None
        if fixture.status != "pending" and staff_queue:
            assigned_to = staff_queue[0].id
        session.add(
            PendingRequest(
                clinic_id=tenant.clinic_id,
                patient_id=patient.id,
                request_type=fixture.request_type,
                status=fixture.status,
                details=fixture.details,
                assigned_to=assigned_to,
            )
        )
        counters["pending_requests"] += 1
    session.flush()


def _fixture_public_ids(slug: str, prefix: str, key: str) -> tuple[str, ...]:
    """Both spellings a demo row can have, newest first.

    The pre-tenancy seed named fixture rows ``demo-<key>``; tenancy added the
    clinic slice so two tenants' fixtures could never share a public id. An
    upgraded file still holds the old spelling, so the lookup has to recognise
    it -- otherwise the first ``make seed`` would duplicate every fixture
    conversation and proposal instead of skipping it.
    """
    bare = key.split(":", 1)[-1]
    return (f"{prefix}-{slug[:12]}-{bare}", f"{prefix}-{bare}")


def _seed_conversations(
    session: Session,
    tenant: TenantSeed,
    patients: dict[str, Patient],
    counters: defaultdict[str, int],
) -> dict[str, Conversation]:
    generation = generations.get_generation(
        session, clinic_id=tenant.clinic_id
    ) or generations.new_generation()
    result: dict[str, Conversation] = {}
    for fixture in tenant.plan.conversations:
        public_ids = _fixture_public_ids(tenant.slug, "demo", fixture.key)
        public_id = public_ids[0]
        existing = session.scalar(
            select(Conversation).where(Conversation.public_id.in_(public_ids))
        )
        if existing:
            counters["skipped"] += 1
            result[fixture.key] = existing
            continue

        started_at = tenant.config.now() + timedelta(days=fixture.day_offset)
        conversation = Conversation(
            clinic_id=tenant.clinic_id,
            public_id=public_id,
            status=fixture.status,
            caller_phone=fixture.caller_phone,
            patient_id=patients[fixture.patient_key].id,
            reset_generation=generation,
            started_at=started_at,
            ended_at=started_at if fixture.status == "closed" else None,
        )
        session.add(conversation)
        session.flush()
        for sequence, (role, content, minute_offset) in enumerate(fixture.messages, start=1):
            session.add(
                Message(
                    clinic_id=tenant.clinic_id,
                    conversation_id=conversation.id,
                    role=role,
                    content=content,
                    sequence=sequence,
                    created_at=started_at + timedelta(minutes=minute_offset),
                )
            )
            counters["messages"] += 1
        counters["conversations"] += 1
        result[fixture.key] = conversation
    session.flush()
    return result


def _seed_proposals(
    session: Session,
    tenant: TenantSeed,
    conversations: dict[str, Conversation],
    providers: dict[str, Provider],
    patients: dict[str, Patient],
    types: dict[str, AppointmentType],
    anchor: date,
    counters: defaultdict[str, int],
) -> None:
    config = tenant.config
    generation = generations.get_generation(
        session, clinic_id=tenant.clinic_id
    ) or generations.new_generation()
    for fixture in tenant.plan.proposals:
        public_ids = _fixture_public_ids(tenant.slug, "demo-proposal", fixture.key)
        public_id = public_ids[0]
        if session.scalar(
            select(BookingProposal).where(BookingProposal.public_id.in_(public_ids))
        ):
            counters["skipped"] += 1
            continue

        conversation = conversations[fixture.conversation_key]
        proposal = BookingProposal(
            clinic_id=tenant.clinic_id,
            public_id=public_id,
            conversation_id=conversation.id,
            status=fixture.status,
            summary=fixture.summary,
            reset_generation=generation,
        )
        session.add(proposal)
        session.flush()

        for order_index, item in enumerate(fixture.items):
            day = anchor + timedelta(days=item.day_offset)
            proposed_start = (
                datetime.combine(day, config.open_time) + config.slot_length * item.slot_index
            )
            slot = _slot_at(session, tenant, providers[item.provider_key].id, proposed_start)
            session.add(
                ProposalItem(
                    clinic_id=tenant.clinic_id,
                    proposal_id=proposal.id,
                    patient_id=patients[item.patient_key].id,
                    provider_id=providers[item.provider_key].id,
                    appointment_type_id=types[item.type_code].id,
                    availability_slot_id=slot.id if slot else None,
                    proposed_starts_at=proposed_start,
                    duration_minutes=types[item.type_code].duration_minutes,
                    order_index=order_index,
                )
            )
            counters["proposal_items"] += 1
        counters["proposals"] += 1
    session.flush()


def _seed_idempotency(
    session: Session, tenant: TenantSeed, counters: defaultdict[str, int]
) -> None:
    """One completed record so the table is non-empty for demonstrations."""
    key, scope = "demo-seed", "demo.seed"
    if session.scalar(
        select(IdempotencyRecord).where(
            IdempotencyRecord.clinic_id == tenant.clinic_id,
            IdempotencyRecord.key == key,
            IdempotencyRecord.scope == scope,
        )
    ):
        counters["skipped"] += 1
        return
    session.add(
        IdempotencyRecord(
            clinic_id=tenant.clinic_id,
            key=key,
            scope=scope,
            response_status=200,
            response_body=json.dumps({"seeded": True}),
            reset_generation=generations.get_generation(session, clinic_id=tenant.clinic_id)
            or "unknown",
            created_at=utcnow(),
        )
    )
    session.flush()


