def seed_tenant(
    session: Session, tenant: TenantSeed, *, today: date | None = None
) -> SeedSummary:
    """Apply one tenant's fixtures, skipping anything that already exists."""
    # Two dates, deliberately different. ``start`` is the clinic-local today and
    # is where the forward grid begins: the demo has to be bookable in the week
    # it is seeded in, not from the following Monday. ``anchor`` is the next
    # Monday at/after it, which only the fixture appointments use -- that keeps
    # their weekdays stable no matter which day the demo is created on.
    start = today or tenant.config.today()
    anchor = anchor_date(tenant.config, start)
    counters: defaultdict[str, int] = defaultdict(int)

    generations.ensure_generation(session, clinic_id=tenant.clinic_id)

    providers = _seed_providers(session, tenant, counters)
    patients, families = _seed_families_and_patients(session, tenant, counters)
    types = _seed_appointment_types(session, tenant, counters)
    _seed_slots(
        session,
        tenant,
        providers,
        today=start,
        anchor=anchor,
        counters=counters,
    )
    _seed_appointments(session, tenant, providers, patients, types, families, anchor, counters)
    staff = _seed_staff(session, tenant, counters)
    _seed_alerts(session, tenant, patients, counters)
    _seed_pending_requests(session, tenant, patients, staff, counters)
    conversations = _seed_conversations(session, tenant, patients, counters)
    _seed_proposals(session, tenant, conversations, providers, patients, types, anchor, counters)
    _seed_idempotency(session, tenant, counters)
    _touch_manifest(session, tenant)

    audit.record(
        session,
        action="demo.seed",
        entity_type="fixture_set",
        entity_id=FIXTURE_SET,
        details=dict(sorted(counters.items())),
    )

    summary = SeedSummary(
        anchor_date=anchor,
        horizon_days=tenant.config.seed_horizon_days,
        providers_created=counters["providers"],
        patients_created=counters["patients"],
        families_created=counters["families"],
        appointment_types_created=counters["appointment_types"],
        slots_created=counters["slots"],
        appointments_created=counters["appointments"],
        staff_created=counters["staff"],
        alerts_created=counters["alerts"],
        pending_requests_created=counters["pending_requests"],
        conversations_created=counters["conversations"],
        messages_created=counters["messages"],
        proposals_created=counters["proposals"],
        proposal_items_created=counters["proposal_items"],
        claim_conflicts=counters["claim_conflicts"],
        skipped_existing=counters["skipped"],
    )
    logger.info("Seed complete for %s: %s", tenant.slug, summary.as_dict())
    return summary


def seed_database(
    today: date | None = None, *, slugs: list[str] | None = None
) -> dict[str, SeedSummary]:
    """Seed every named tenant (all of them by default). Keyed by slug.

    Tenant rows are ensured first, in one transaction, because the fixture rows
    below carry a ``clinic_id`` foreign key. Then each tenant is seeded through
    its own session bound to that clinic: the insert guard in
    :mod:`app.models.base` then rejects a row written for the wrong tenant
    instead of letting it land in another clinic's world.
    """
    wanted = [plan for plan in TENANT_PLANS if slugs is None or plan.slug in slugs]
    with session_scope() as session:
        ensure_clinic_rows(session, tuple(wanted))
        session.commit()
        resolved = [(plan, tenant_for(session, plan)) for plan in wanted]

    summaries: dict[str, SeedSummary] = {}
    for plan, tenant in resolved:
        if tenant is None:
            logger.warning("Clinic %s could not be resolved; not seeded.", plan.slug)
            continue
        with session_scope(tenant.clinic_id) as session:
            summaries[tenant.slug] = seed_tenant(session, tenant, today=today)
            session.commit()
    return summaries


def database_is_seeded(session: Session, clinic_id: int | None = None) -> bool:
    """True when the fixture manifest has been applied for this tenant.

    With no ``clinic_id`` the session's own binding is used; ``None`` for both
    means "has anything at all been seeded", which is what the bootstrap check
    needs before any tenant exists.
    """
    statement = select(func.count()).select_from(SeedManifest).where(
        SeedManifest.fixture_set == FIXTURE_SET
    )
    if clinic_id is not None:
        statement = statement.where(SeedManifest.clinic_id == clinic_id)
    elif session.info.get("clinic_id") is None:
        statement = statement.execution_options(tenant_scoped=False)
    return (session.scalar(statement) or 0) > 0


def is_empty_database(session: Session, clinic_id: int | None = None) -> bool:
    """True when *this* tenant has no patients, providers, or fixtures at all.

    ``func.count()`` is a projection, so the ORM criteria net never reaches it:
    the clinic predicate below is the only thing keeping one clinic's emptiness
    from being judged by another clinic's rows.
    """
    owner = clinic_id if clinic_id is not None else bound_clinic_id(session)
    patient_count = session.scalar(
        select(func.count())
        .select_from(Patient)
        .where(*([Patient.clinic_id == owner] if owner is not None else []))
        .execution_options(tenant_scoped=False)
    )
    provider_count = session.scalar(
        select(func.count())
        .select_from(Provider)
        .where(*([Provider.clinic_id == owner] if owner is not None else []))
        .execution_options(tenant_scoped=False)
    )
    return not patient_count and not provider_count


