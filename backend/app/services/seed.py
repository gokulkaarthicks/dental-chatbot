@dataclass(frozen=True)
class TenantSeed:
    """One tenant's seeding inputs: its row id, its grid, its fixtures."""

    clinic_id: int
    slug: str
    config: SchedulingConfig
    template: TenantSeedPlan

    @property
    def plan(self):
        """The tenant's fixture tables."""
        return self.template.fixtures


