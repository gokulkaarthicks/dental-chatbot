def _clinic_public_id(slug: str) -> str:
    digest = hashlib.sha256(slug.encode()).hexdigest()[:12]
    return f"clinic_{digest}"


def ensure_clinic_rows(session: Session, plans: tuple[TenantSeedPlan, ...] = TENANT_PLANS) -> None:
    """Create or refresh the ``clinics`` rows and their knowledge tables.

    Runs before any fixture backfill, because every tenant row is the target of
    a ``clinic_id`` foreign key: the children cannot exist first.

    Existing rows are *updated* rather than left alone. A demo clinic whose
    hours were edited in the database is a configuration change, but re-running
    ``make seed`` is how a fresh clone gets its data, so the template has to win
    here -- otherwise a partial seed leaves a clinic with tenant 1's fixtures and
    tenant 2's hours.
    """
    for plan in plans:
        clinic = find_clinic(session, plan.slug)
        if clinic is None:
            clinic = Clinic(slug=plan.slug, public_id=_clinic_public_id(plan.slug))
            session.add(clinic)
        _apply_clinic_template(clinic, plan)
        session.flush()
        _sync_insurance_plans(session, clinic, plan)
        _sync_policies(session, clinic, plan)
    session.flush()


def _apply_clinic_template(clinic: Clinic, plan: TenantSeedPlan) -> None:
    config = plan.clinic
    scheduling = plan.scheduling
    clinic.name = config.name
    clinic.legal_note = config.legal_note
    clinic.address_line1 = config.address_line1
    clinic.address_line2 = config.address_line2
    clinic.city = config.city
    clinic.state = config.state
    clinic.postal_code = config.postal_code
    clinic.phone = config.phone
    clinic.email = config.email
    clinic.timezone = scheduling.timezone_name
    clinic.slot_minutes = scheduling.slot_minutes
    clinic.open_time = scheduling.open_time
    clinic.close_time = scheduling.close_time
    clinic.open_weekdays = sorted(scheduling.open_weekdays)
    clinic.closed_days = list(scheduling.closed_day_labels)
    clinic.seed_horizon_days = scheduling.seed_horizon_days
    clinic.parking_note = config.parking_note
    clinic.timezone_note = config.timezone_note
    clinic.insurance_note = plan.insurance_note
    clinic.self_pay_label = plan.self_pay_label
    clinic.fictional = config.fictional
    clinic.is_default = plan.is_default
    clinic.active = True


def _sync_insurance_plans(session: Session, clinic: Clinic, plan: TenantSeedPlan) -> None:
    stored = {
        row.name: row for row in session.scalars(
            select(ClinicInsurancePlan).where(ClinicInsurancePlan.clinic_id == clinic.id)
        )
    }
    wanted = {item.name: item for item in plan.insurance_plans}
    for name, row in stored.items():
        if name not in wanted:
            session.delete(row)
    for name, item in wanted.items():
        row = stored.get(name)
        if row is None:
            session.add(
                ClinicInsurancePlan(
                    clinic_id=clinic.id, name=item.name, accepted=item.accepted, note=item.note
                )
            )
        else:
            row.accepted = item.accepted
            row.note = item.note


def _sync_policies(session: Session, clinic: Clinic, plan: TenantSeedPlan) -> None:
    stored = {
        row.topic: row
        for row in session.scalars(select(ClinicPolicy).where(ClinicPolicy.clinic_id == clinic.id))
    }
    wanted = {item.topic: item for item in plan.policies}
    for topic, row in stored.items():
        if topic not in wanted:
            session.delete(row)
    for topic, item in wanted.items():
        row = stored.get(topic)
        if row is None:
            session.add(
                ClinicPolicy(
                    clinic_id=clinic.id,
                    topic=item.topic,
                    question=item.question,
                    answer=item.answer,
                    keywords=list(item.keywords),
                )
            )
        else:
            row.question = item.question
            row.answer = item.answer
            row.keywords = list(item.keywords)
    session.flush()


def tenant_for(session: Session, plan: TenantSeedPlan) -> TenantSeed | None:
    clinic = find_clinic(session, plan.slug)
    if clinic is None:
        return None
    return TenantSeed(
        clinic_id=clinic.id,
        slug=clinic.slug,
        config=scheduling_config_for(clinic),
        template=plan,
    )


