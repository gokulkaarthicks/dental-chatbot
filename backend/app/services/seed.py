def _checksum(tenant: TenantSeed) -> str:
    plan = tenant.plan
    payload = {
        "version": FIXTURE_VERSION,
        "clinic": tenant.slug,
        "slot_minutes": tenant.config.slot_minutes,
        "providers": [item.key for item in plan.providers],
        "families": [item.key for item in plan.families],
        "patients": [item.key for item in plan.patients],
        "types": [item.code for item in plan.appointment_types],
        "appointments": [item.key for item in plan.upcoming + plan.past],
        "staff": [item.key for item in plan.staff],
    }
    return hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()


def _touch_manifest(session: Session, tenant: TenantSeed) -> None:
    now = utcnow()
    manifest = session.scalar(
        select(SeedManifest).where(
            SeedManifest.fixture_set == FIXTURE_SET,
            SeedManifest.clinic_id == tenant.clinic_id,
        )
    )
    if manifest is None:
        session.add(
            SeedManifest(
                clinic_id=tenant.clinic_id,
                fixture_set=FIXTURE_SET,
                fixture_version=FIXTURE_VERSION,
                checksum=_checksum(tenant),
                applied_at=now,
                created_at=now,
                updated_at=now,
            )
        )
    else:
        manifest.fixture_version = FIXTURE_VERSION
        manifest.checksum = _checksum(tenant)
        manifest.applied_at = now
    generations.mark_seeded(session, now, clinic_id=tenant.clinic_id)
    session.flush()


def _slot_at(
    session: Session, tenant: TenantSeed, provider_id: int, starts_at: datetime
) -> AvailabilitySlot | None:
    return session.scalar(
        select(AvailabilitySlot).where(
            AvailabilitySlot.clinic_id == tenant.clinic_id,
            AvailabilitySlot.provider_id == provider_id,
            AvailabilitySlot.starts_at == starts_at,
        )
    )


def _covered_slot_days(
    session: Session, tenant: TenantSeed, provider_id: int, *, after: datetime | None = None
) -> set:
    """Distinct stored dates for one provider. A projection, so scoped by hand."""
    statement = select(func.date(AvailabilitySlot.starts_at)).where(
        AvailabilitySlot.clinic_id == tenant.clinic_id,
        AvailabilitySlot.provider_id == provider_id,
    )
    if after is not None:
        statement = statement.where(AvailabilitySlot.starts_at >= after)
    return set(session.scalars(statement.execution_options(tenant_scoped=False)))


