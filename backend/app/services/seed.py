"""Idempotent demo-data seeding, per tenant.

Design rules
------------
* Every seeded row carries a stable ``seed_key`` (or an equivalent natural key).
  Seeding looks rows up and creates only what is missing, so ``make seed`` can
  run repeatedly without duplicating data and without deleting anything.
* Slots are generated only for days that currently have **no** slots for the
  provider. That gives a rolling horizon on later runs while never touching
  existing (possibly occupied) intervals.
* Everything happens inside one transaction per tenant, so a failed seed rolls
  back whole -- and one clinic's seed cannot half-write another's world.
* The anchor date is the next Monday at/after *that clinic's* today, which is
  deterministic per day and keeps fixture weekdays stable.

Tenancy
-------
Nothing here reads a clinic constant. A :class:`TenantSeed` carries the clinic's
id, its ``SchedulingConfig`` (grid, hours, days, horizon) and its fixture plan,
and every row written below is stamped with ``tenant.clinic_id``. The grid is
built from ``config.open_time``/``close_time``/``slot_length``, so tenant 2's
20-minute Tuesday-Saturday calendar is generated by the same code as tenant 1's
30-minute Monday-Saturday one rather than by a special case.
"""

